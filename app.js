function updateKT() {
  const regionEl = document.getElementById('region');
  const vehicleEl = document.getElementById('vehicle');
  const cityBox = document.getElementById('cityBlock');
  const cityEl = document.getElementById('city');
  
  const regionCode = regionEl.value;
  // Проверяем, выбрана ли категория тракторов
  const isTractor = vehicleEl.options[vehicleEl.selectedIndex].text.includes('Тракторы');

  // Выбираем, какой словарь использовать
  const activeMap = isTractor ? KT_TRACTOR_MAP : KT_MAP;

  const regionData = activeMap[regionCode];

  if (!regionData) {
    cityBox.style.display = 'none';
    currentKT = 1;
    return;
  }

  if (regionData.baseKT !== null) {
    // Если для региона фиксированный КТ
    cityBox.style.display = 'none';
    currentKT = regionData.baseKT;
  } else {
    // Если нужно выбирать город
    cityBox.style.display = 'block';
    cityEl.innerHTML = '';
    
    for (const name in regionData.cities) {
      const opt = document.createElement('option');
      opt.value = regionData.cities[name];
      opt.textContent = name;
      cityEl.appendChild(opt);
    }
    // Устанавливаем КТ из первого города в списке
    currentKT = parseFloat(cityEl.value);
  }
}

function calcOSAGO() {
  const vehicleEl = document.getElementById('vehicle');
  const noLimits = document.getElementById('noLimits').checked;
  const kbmEl = document.getElementById('kbm');
  const ksSelect = document.getElementById('ks');
  const birthInput = document.getElementById('birthDate');
  const expInput = document.getElementById('experienceDate');
  const kvsBlock = document.getElementById('kvsBlock');

  const basePrice = parseFloat(vehicleEl.value) || 0;
  const vehicleText = vehicleEl.options[vehicleEl.selectedIndex].text;

  // 1. Определяем тип ТС
  const isMoto = vehicleText.includes('A ') || vehicleText.includes('M ');
  const isAuto = vehicleText.includes('B ') || vehicleText.includes('Такси');

  // 2. Рассчитываем коэффициенты
  let ko = 1, kbm = parseFloat(kbmEl.value) || 1, kvs = 1, ks = parseFloat(ksSelect.value) || 1;

  if (noLimits) {
    ko = 3.16; 
    kbm = 1.17; 
    kvs = 1;
    if(kbmEl) kbmEl.disabled = true;
    if(birthInput) birthInput.disabled = true;
    if(expInput) expInput.disabled = true;
  } else {
    if(kbmEl) kbmEl.disabled = false;
    if(birthInput) birthInput.disabled = false;
    if(expInput) expInput.disabled = false;
    const age = getAgeFromStr(birthInput.value);
    const exp = getAgeFromStr(expInput.value);
    kvs = getKvsValue(age, exp, isMoto);
  }
  
  if (kvsBlock) {
  // Если галочка стоит, скрываем блок, иначе - показываем
  kvsBlock.style.display = noLimits ? 'none' : 'block';
}

  // 3. Мощность (KM)
  let km = 1;
  const pMotoBlock = document.getElementById('powerMoto');
  const pAutoBlock = document.getElementById('powerAuto');

  if (pMotoBlock) pMotoBlock.style.display = isMoto ? 'block' : 'none';
  if (pAutoBlock) pAutoBlock.style.display = isAuto ? 'block' : 'none';

  if (isMoto) {
    const pVal = document.getElementById('powerMotoValue');
    km = pVal ? parseFloat(pVal.value) : 1;
  } else if (isAuto) {
    const pVal = document.getElementById('powerAutoValue');
    km = pVal ? parseFloat(pVal.value) : 1;
  }

  // 4. ИТОГОВЫЙ РАСЧЕТ
  const final = Math.round(basePrice * currentKT * kbm * kvs * ko * km * ks);

  // 5. ЗАПОЛНЕНИЕ ТАБЛИЦЫ СПРАВА
  // Обновляем итоговую сумму
  const resultEl = document.getElementById('result');
  if (resultEl) resultEl.innerText = `${final.toLocaleString()} ₽`;
  
  // Функция для безопасного обновления ячеек таблицы
  const updateTableCell = (id, value) => {
    const el = document.getElementById(id);
    if (el) el.innerText = value;
  };

  updateTableCell('val-bt', basePrice);
  updateTableCell('val-kt', currentKT);
  updateTableCell('val-kbm', kbm);
  updateTableCell('val-kvs', kvs);
  updateTableCell('val-ko', ko);
  updateTableCell('val-km', km);
  updateTableCell('val-ks', ks);
}

