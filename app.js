// Маска для ввода даты (ДД.ММ.ГГГГ)
function applyDateMask(el) {
  el.addEventListener('input', (e) => {
    let v = e.target.value.replace(/\D/g, '');
    if (v.length > 8) v = v.substring(0, 8);
    if (v.length > 4) v = v.substring(0, 2) + '.' + v.substring(2, 4) + '.' + v.substring(4);
    else if (v.length > 2) v = v.substring(0, 2) + '.' + v.substring(2);
    e.target.value = v;
  });
}

// Парсинг даты из формата ДД.ММ.ГГГГ
function getAgeFromStr(dateStr) {
  if (!dateStr || dateStr.length < 10) return 0;
  const parts = dateStr.split('.');
  const birthDate = new Date(parts[2], parts[1] - 1, parts[0]);
  const now = new Date();
  let age = now.getFullYear() - birthDate.getFullYear();
  const m = now.getMonth() - birthDate.getMonth();
  if (m < 0 || (m === 0 && now.getDate() < birthDate.getDate())) age--;
  return age < 0 ? 0 : age;
}

function getKvsValue(age, exp, isMoto) {
  const table = isMoto ? KVS_MOTO_TABLE : KVS_AUTO_TABLE;
  
  // 1. Определяем индекс строки (Возраст)
  // Для обеих ваших новых таблиц сетка возраста совпадает (8 строк)
  let rowIndex = age >= 60 ? 7 : age >= 50 ? 6 : age >= 40 ? 5 : age >= 35 ? 4 : 
                 age >= 30 ? 3 : age >= 25 ? 2 : age >= 22 ? 1 : 0;

  // 2. Определяем идеальный индекс столбца (Стаж)
  // 0, 1, 2, 3, 4, 5-6(5), 7-9(6), 10-14(7)
  let targetCol = exp >= 14 ? 7 : exp >= 10 ? 6 : exp >= 7 ? 5 : exp >= 5 ? 4 : 
                  exp >= 3 ? 3 : exp >= 2 ? 2 : exp >= 1 ? 1 : 0;

  // 3. ПРЕДОХРАНИТЕЛЬ:
  // Если в этой строке меньше столбцов, чем нам нужно (например, в строке [0] всего 5 элементов),
  // мы берем последний доступный элемент в этой строке.
  const currentRow = table[rowIndex];
  const colIndex = Math.min(targetCol, currentRow.length - 1);

  return currentRow[colIndex];
}

